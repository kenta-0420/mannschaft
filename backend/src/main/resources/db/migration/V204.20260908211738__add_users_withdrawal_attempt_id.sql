-- =====================================================================
-- 柱③-B 組織契約の請求担当と個人支払手段の分離（CMP-260901-1538・PR-3）
-- 退会申請ごとに一意な識別子を払い出す（Codex 単点確認・指定設計）
-- =====================================================================
-- 設計書: docs/architecture/billing_payer_handover_design.md §6.1 (5)(7)
--
-- 【なぜ列を足すのか】
-- 退会試行の「同一性」を推測で判定していたために、同じ穴を3度空けた。
--   1回目: 冪等キーに時刻（users.deleted_at）を使った
--          → 本番の deleted_at は DATETIME（小数秒なし）で同一秒内の再退会が衝突する
--   2回目: キーの値を試行番号にしたが、払い直しの判定を時刻の一致で行っていた
--          → 判定側に同じ穴が残った
--   3回目: 判定を作業行の状態（PENDING/FAILED なら同一試行）に替えた
--          → 「取消イベントが追いつく前に次の退会イベントが走る」と、行はまだ前世代の
--            PENDING のままなので別世代を同一試行と誤認する
--
-- 状態や時刻から【推測】するのをやめ、退会側に世代の【正本】を持たせる。
-- requestWithdrawal のたびに新規採番するため、同一秒だろうと再退会なら必ず別の値になる。
--
-- cancelWithdrawal では消さず据え置く（取消しても値は残るが、次の退会申請で必ず更新される）。
-- 既存の退会申請中ユーザーには採番済みの値をバックフィルする（NULL のまま残すと
-- 「退会中なのに識別子が無い」行が生まれ、判定側が退会していないと誤答しうるため）。
-- =====================================================================
ALTER TABLE users
    ADD COLUMN withdrawal_attempt_id BINARY(16) NULL
        COMMENT '退会申請ごとに一意な識別子（UUID）。退会試行の世代の正本。requestWithdrawal で毎回新規採番する'
        AFTER purge_started_at;

-- 既に退会申請中の行へバックフィル（UUID() は行ごとに異なる値を返す）。
UPDATE users
SET withdrawal_attempt_id = UUID_TO_BIN(UUID())
WHERE deleted_at IS NOT NULL
  AND withdrawal_attempt_id IS NULL;
